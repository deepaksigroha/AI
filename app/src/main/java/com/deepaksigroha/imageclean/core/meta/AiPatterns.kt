package com.deepaksigroha.imageclean.core.meta

/**
 * Known AI-related metadata vocabulary.
 * Sources: IPTC NewsCodes "digitalsourcetype" vocabulary, C2PA actions specification,
 * and metadata written by common image generators and editors.
 */
object AiPatterns {

    enum class SourceTypeClass { AI_GENERATED, AI_ASSISTED, NOT_AI, OTHER }

    enum class SourceType(val code: String, val label: String, val cls: SourceTypeClass) {
        TRAINED_ALGORITHMIC("trainedAlgorithmicMedia", "Created using generative AI (trainedAlgorithmicMedia)", SourceTypeClass.AI_GENERATED),
        COMPOSITE_TRAINED("compositeWithTrainedAlgorithmicMedia", "Composite including generative-AI elements", SourceTypeClass.AI_ASSISTED),
        ALGORITHMICALLY_ENHANCED("algorithmicallyEnhanced", "Algorithmically enhanced", SourceTypeClass.AI_ASSISTED),
        ALGORITHMIC("algorithmicMedia", "Pure algorithmic media (non-trained)", SourceTypeClass.OTHER),
        COMPOSITE_SYNTHETIC("compositeSynthetic", "Composite including synthetic elements", SourceTypeClass.AI_ASSISTED),
        DIGITAL_CREATION("digitalCreation", "Digital creation (non-AI)", SourceTypeClass.OTHER),
        DIGITAL_CAPTURE("digitalCapture", "Original digital capture", SourceTypeClass.NOT_AI),
        COMPUTATIONAL_CAPTURE("computationalCapture", "Computational capture (phone processing)", SourceTypeClass.NOT_AI),
        NEGATIVE_FILM("negativeFilm", "Scanned negative film", SourceTypeClass.NOT_AI),
        POSITIVE_FILM("positiveFilm", "Scanned positive film", SourceTypeClass.NOT_AI),
        PRINT("print", "Scanned print", SourceTypeClass.NOT_AI),
        SCREEN_CAPTURE("screenCapture", "Screen capture", SourceTypeClass.OTHER),
        MINOR_HUMAN_EDITS("minorHumanEdits", "Minor human edits", SourceTypeClass.NOT_AI),
        COMPOSITE_CAPTURE("compositeCapture", "Composite of captures", SourceTypeClass.NOT_AI),
        COMPOSITE("composite", "Composite", SourceTypeClass.OTHER),
        DATA_DRIVEN("dataDrivenMedia", "Data-driven media", SourceTypeClass.OTHER),
        VIRTUAL_RECORDING("virtualRecording", "Virtual recording", SourceTypeClass.OTHER),
    }

    /** Matches a DigitalSourceType URI or bare code (longest code first so 'composite…' wins over 'algorithmicMedia'). */
    fun matchSourceType(value: String): SourceType? {
        if (value.isBlank()) return null
        val v = value.trim()
        val tail = v.substringAfterLast('/').substringAfterLast('#').trim()
        SourceType.entries.firstOrNull { it.code.equals(tail, ignoreCase = true) }?.let { return it }
        if (!v.contains("digitalsourcetype", true)) return null
        return SourceType.entries.sortedByDescending { it.code.length }.firstOrNull { v.contains(it.code, ignoreCase = true) }
    }

    /** Generator / tool names. Matching is case-insensitive on word-ish boundaries. */
    private val generators = listOf(
        "DALL-E" to Regex("""dall[\s\-·]?e""", RegexOption.IGNORE_CASE),
        "ChatGPT / OpenAI" to Regex("""\b(chatgpt|openai|gpt-?4o|gpt-image)\b""", RegexOption.IGNORE_CASE),
        "Midjourney" to Regex("""midjourney""", RegexOption.IGNORE_CASE),
        "Stable Diffusion" to Regex("""stable[\s_\-]?diffusion|\bsdxl\b|stability\.?ai""", RegexOption.IGNORE_CASE),
        "Adobe Firefly" to Regex("""firefly""", RegexOption.IGNORE_CASE),
        "Adobe Generative Fill/Expand" to Regex("""generative (fill|expand)""", RegexOption.IGNORE_CASE),
        "Google Imagen / Gemini" to Regex("""\b(imagen|gemini|google ai|synthid|nano[\s\-]?banana)\b""", RegexOption.IGNORE_CASE),
        "Microsoft Designer / Bing Image Creator" to Regex("""bing image creator|microsoft designer|copilot designer""", RegexOption.IGNORE_CASE),
        "Meta AI" to Regex("""\b(meta ai|imagined with ai)\b""", RegexOption.IGNORE_CASE),
        "Leonardo.Ai" to Regex("""leonardo\.?ai""", RegexOption.IGNORE_CASE),
        "Ideogram" to Regex("""ideogram""", RegexOption.IGNORE_CASE),
        "FLUX (Black Forest Labs)" to Regex("""\bflux(\.1)?\b|black forest labs""", RegexOption.IGNORE_CASE),
        "NovelAI" to Regex("""novelai""", RegexOption.IGNORE_CASE),
        "ComfyUI" to Regex("""comfyui""", RegexOption.IGNORE_CASE),
        "AUTOMATIC1111 / Forge" to Regex("""automatic1111|stable-diffusion-webui|sd-webui-forge""", RegexOption.IGNORE_CASE),
        "InvokeAI" to Regex("""invokeai""", RegexOption.IGNORE_CASE),
        "Runway" to Regex("""runwayml|\brunway\b""", RegexOption.IGNORE_CASE),
        "Grok / xAI" to Regex("""\b(grok|x\.ai)\b""", RegexOption.IGNORE_CASE),
        "Canva Magic Media" to Regex("""magic media|canva ai""", RegexOption.IGNORE_CASE),
        "Samsung Generative Edit" to Regex("""generative edit""", RegexOption.IGNORE_CASE),
        "Google Magic Editor" to Regex("""magic editor""", RegexOption.IGNORE_CASE),
        "Generic AI marker" to Regex("""\b(ai[\s\-]generated|generated by ai|made with ai|ai[\s\-]edited|text-to-image)\b""", RegexOption.IGNORE_CASE),
    )

    fun matchGenerator(text: String?): String? {
        if (text.isNullOrBlank()) return null
        return generators.firstOrNull { it.second.containsMatchIn(text) }?.first
    }

    /** XMP / text keys that, by their presence, indicate generative-AI metadata. */
    fun isAiPropertyKey(lowerKey: String): Boolean =
        lowerKey.endsWith(":ai_generated") || lowerKey.endsWith(":aigenerated") ||
            lowerKey.contains("generativeai") || lowerKey.endsWith(":prompt") ||
            lowerKey.endsWith(":aisystemused") || lowerKey.endsWith(":aipromptinformation") ||
            lowerKey.endsWith(":aisystemversionused") || lowerKey.endsWith(":aipromptwritername")

    /** PNG text keys written by local diffusion UIs. */
    val aiPngTextKeys = mapOf(
        "parameters" to "AUTOMATIC1111/Forge generation parameters",
        "prompt" to "ComfyUI prompt graph",
        "workflow" to "ComfyUI workflow",
        "Dream" to "InvokeAI/Dream parameters",
        "sd-metadata" to "InvokeAI metadata",
        "invokeai_metadata" to "InvokeAI metadata",
        "Comment" to "Generator parameters (e.g. NovelAI)",
        "Software" to "",
        "Description" to "",
        "Source" to "",
        "generation_data" to "Generation data",
        "aesthetic_score" to "Diffusion aesthetic score",
    )

    /** C2PA action names that indicate AI involvement. */
    val aiActionHints = listOf("c2pa.created", "c2pa.edited", "c2pa.placed", "c2pa.opened", "c2pa.converted")
}
